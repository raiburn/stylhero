// Generates src/theme/tokens.ts from ../tokens.json (the source of truth shared with @stylhero/ui).
// CSS units become React Native numbers: "16px" -> 16, letterSpacing "-0.02em" -> px at that size.
// Shadows stay as CSS strings: React Native >= 0.76 (New Architecture) supports `boxShadow`.
// Run: npm run tokens   (also runs before every build; CI fails if the output is not committed)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, "..", "..", "tokens.json"), "utf8"));
const out = join(here, "..", "src", "theme", "tokens.ts");

const themes = tokens.color.themes.map((t) => t.id);
const [baseTheme] = themes;
const valueIn = (token, theme) =>
  typeof token.value === "string" ? token.value : token.value[theme] ?? token.value[baseTheme];

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const px = (value, where) => {
  const m = /^(-?\d+(?:\.\d+)?)px$/.exec(String(value));
  if (!m) throw new Error(`${where}: expected a px value, got "${value}"`);
  return Number(m[1]);
};
const round = (n) => Math.round(n * 100) / 100;

// ---------- colors ----------
const colors = {};
for (const theme of themes) {
  colors[theme] = {};
  for (const t of tokens.color.tokens) colors[theme][camel(t.name)] = valueIn(t, theme);
}

// ---------- spacing / radius ----------
const stripPrefix = (name, prefix) => name.replace(new RegExp(`^${prefix}-`), "");
const spacing = Object.fromEntries(
  tokens.spacing.tokens.map((t) => [stripPrefix(t.name, "space"), px(t.value, t.name)])
);
const radius = Object.fromEntries(
  tokens.radius.tokens.map((t) => [stripPrefix(t.name, "radius"), px(t.value, t.name)])
);

// ---------- typography ----------
const typography = {};
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    const fontSize = px(s.fontSize, `type ${s.name}`);
    const style = {
      family: group.family,
      fontSize,
      lineHeight: px(s.lineHeight, `type ${s.name}`),
      fontWeight: String(s.fontWeight),
    };
    if (s.letterSpacing) {
      const em = /^(-?\d*\.?\d+)em$/.exec(s.letterSpacing);
      if (!em) throw new Error(`type ${s.name}: letterSpacing must be in em, got "${s.letterSpacing}"`);
      style.letterSpacing = round(Number(em[1]) * fontSize);
    }
    typography[s.name] = style;
  }
}

// ---------- shadows ----------
const shadows = {};
for (const theme of themes) {
  shadows[theme] = {};
  for (const t of tokens.shadow.tokens) shadows[theme][stripPrefix(t.name, "shadow")] = valueIn(t, theme);
}

// ---------- write ----------
const json = (v) => JSON.stringify(v, null, 2);
// Unquoted numeric keys so `spacing[4]` and <Stack gap={4}> type-check with numbers.
const numericKeys = (obj) =>
  `{\n${Object.entries(obj).map(([k, v]) => `  ${/^\d+$/.test(k) ? k : JSON.stringify(k)}: ${JSON.stringify(v)}`).join(",\n")}\n}`;
const body = `// GENERATED by scripts/build-tokens.mjs from tokens.json. Do not edit by hand.
// Run \`npm run tokens\` after changing tokens.json.

export const colorSchemes = ${json(themes)} as const;
export type ColorScheme = (typeof colorSchemes)[number];

export const colors = ${json(colors)} as const;
export type ColorToken = keyof (typeof colors)["${baseTheme}"];
export type Colors = Record<ColorToken, string>;

export const spacing = ${numericKeys(spacing)} as const;
export type SpacingToken = keyof typeof spacing;

export const radius = ${json(radius)} as const;
export type RadiusToken = keyof typeof radius;

export const typography = ${json(typography)} as const;
export type TypographyToken = keyof typeof typography;
export type FontFamilyToken = (typeof typography)[TypographyToken]["family"];

export const shadows = ${json(shadows)} as const;
export type ShadowToken = keyof (typeof shadows)["${baseTheme}"];
`;

writeFileSync(out, body);
console.log(`tokens: wrote ${Object.keys(colors[baseTheme]).length} colors x ${themes.length} themes, ` +
  `${Object.keys(spacing).length} spacing, ${Object.keys(radius).length} radius, ` +
  `${Object.keys(typography).length} type styles, ${Object.keys(shadows[baseTheme]).length} shadows`);
